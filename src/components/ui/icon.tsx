export type IconName = keyof typeof ICONS;

export const ICON_NAMES = Object.keys(ICONS) as IconName[];

export function isIconName(name: string | null | undefined): name is IconName {
  return !!name && name in ICONS;
}

/**
 * One icon. `size` is the box in dp; the stroke stays a little under 2 at
 * every size so small and large icons read as the same family.
 */
export function Icon({
  name,
  size = 20,
  color,
  strokeWidth,
  style,
  accessibilityLabel,
}: {
  name: IconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
  style?: StyleProp<ViewStyle>;
  /** For an icon that says something on its own, with no text beside it. */
  accessibilityLabel?: string;
}) {
  const Drawn = ICONS[name];
  return (
    <Drawn
      size={size}
      color={color}
      strokeWidth={strokeWidth ?? (size <= 16 ? 2 : 1.8)}
      style={style}
      // Only when labelled: on web an `accessible={false}` reaches the <svg>
      // as a stray DOM attribute.
      {...(accessibilityLabel ? { accessible: true, accessibilityLabel } : null)}
    />
  );
}
